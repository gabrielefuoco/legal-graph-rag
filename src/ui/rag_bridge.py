"""Asynchronous-to-synchronous bridge for streaming RAG responses in Streamlit."""

import logging
import asyncio
from langchain_core.messages import HumanMessage, AIMessage

from src.rag.supervisor import SupervisorAgent

logger = logging.getLogger(__name__)

def run_async(coro):
    """Execute an asynchronous coroutine within Streamlit's synchronous context."""
    try:
        loop = asyncio.get_event_loop()
    except RuntimeError:
        loop = asyncio.new_event_loop()
        asyncio.set_event_loop(loop)
    return loop.run_until_complete(coro)

async def query_rag_with_trace(supervisor: SupervisorAgent, query: str, config: dict, chat_history: list, status_callback=None) -> tuple:
    """Execute the Supervisor Agent via LangGraph message streaming.

    Args:
        supervisor: Instance of SupervisorAgent.
        query: User input query string.
        config: Configuration dictionary for retrieval and generation.
        chat_history: List of conversation turn dicts ({'role': ..., 'content': ...}).
        status_callback: Optional callback for pipeline execution progress.

    Returns:
        Synchronous generator yielding streamed response tokens.
    """
    try:
        messages = []
        for msg in chat_history:
            if msg["role"] == "user":
                messages.append(HumanMessage(content=msg["content"]))
            elif msg["role"] == "assistant":
                messages.append(AIMessage(content=msg["content"]))
        
        messages.append(HumanMessage(content=query))
        
        graph = supervisor.get_graph(status_callback, config)

        out_chunks = []
        out_trace = {}

        async def async_gen():
            """Stream tokens generated by the supervisor agent."""
            logger.info("Avvio astream_events del Supervisor")
            try:
                # Use stream_mode='messages' to isolate supervisor tokens
                async for msg, metadata in graph.astream(
                    {"messages": messages}, 
                    stream_mode="messages",
                    config={"recursion_limit": 50}
                ):
                    node = metadata.get("langgraph_node")
                    
                    # Intercept output tokens strictly from the supervisor 'agent' node
                    if node == "agent":
                        if msg.content and isinstance(msg.content, str):
                            # Skip intermediate tool call chunks to prevent streaming raw JSON
                            if hasattr(msg, "tool_call_chunks") and msg.tool_call_chunks:
                                pass
                            else:
                                yield msg.content
                    
                    # Synchronize latest chunks and trace state from engine
                    if hasattr(supervisor.engine, "_temp_chunks") and supervisor.engine._temp_chunks:
                        out_chunks.clear()
                        out_chunks.extend(supervisor.engine._temp_chunks)
                    if hasattr(supervisor.engine, "_temp_trace") and supervisor.engine._temp_trace:
                        out_trace.update(supervisor.engine._temp_trace)
            except Exception as e:
                logger.error(f"Errore durante astream: {e}")
                yield f"Errore: {str(e)}"
            
        def sync_gen():
            """Bridge the async generator into a synchronous generator for UI consumption."""
            try:
                loop = asyncio.get_event_loop()
            except RuntimeError:
                loop = asyncio.new_event_loop()
                asyncio.set_event_loop(loop)
            
            agen = async_gen()
            try:
                while True:
                    try:
                        chunk = loop.run_until_complete(agen.__anext__())
                        if chunk:
                            yield chunk
                    except StopAsyncIteration:
                        break
            except Exception as e:
                logger.error(f"Errore durante sync_gen: {e}")
                yield f"Errore tecnico: {str(e)}"

        return sync_gen()

    except Exception as e:
        logger.error(f"Errore: {e}")
        err_msg = str(e)
        def sync_err_gen():
            """Yield a technical error message in case of initialization failure."""
            yield f"Errore tecnico: {err_msg}"
        return [], {}, sync_err_gen()
